"""
Zero-shot evaluation on the held-out test sets from the progressive finetuning splits.

This script evaluates model/fold checkpoints found under:
    results/experiments/complete_experiment/ablations/<model_key>/fold_XX/checkpoints/best_f1.pt

Run:
    python scripts/04_zero_shot_cross_volcano.py

On the repeated 80/20 target-volcano splits generated by script 01b:
    data/prepared_data/progressive_finetuning/<VOLCANO>/fold_XX/test_80.npz

Outputs are written to:
    results/experiments/complete_experiment/zero_shot_cross_volcano/
"""

